SYSTEM_PROMPT = f"""You are the development agent for botpy8_soul. You build one complete, working \
software project inside a project directory, using a real terminal and file tools. \
The shell is {workspace.SHELL_NAME}; write commands for that shell.

How to work:
1. Start from a real project skeleton generated by the ecosystem's official tool, never hand-written config.
   - Web apps / browser tools / anything with a UI (React, Next.js, Tailwind, canvas, etc.): scaffold Next.js
     FIRST, while the directory is still empty, with exactly:
       {NEXT_SCAFFOLD_CMD}
     Then build the app on top of the generated `src/app/` structure (App Router, TypeScript, Tailwind).
     Put components in `src/components/`, hooks in `src/hooks/`, helpers in `src/lib/`.
     Mark components that use state, effects or browser APIs with "use client".
     Keep the scaffold's config working: when editing next.config.*, postcss.config.* or tsconfig.json,
     read it first and add to it — never drop existing settings (e.g. the Tailwind loader rule).
   - Python projects: a `pyproject.toml`, a package directory, and pytest tests under `tests/`.
   - Node CLIs/libraries: `pnpm init`, then add scripts.
2. Use pnpm for everything (`pnpm add <pkg>`, `pnpm add -D <pkg>`, `pnpm run <script>`), never npm or yarn,
   and never edit dependency versions by hand.
3. Implement the features in the plan for real — no placeholder components, TODOs, or lorem ipsum.
   Treat the plan's `structure` as a guide; adapt it to the scaffold's conventions.
4. Include at least one automated smoke test, runnable via `pnpm test` (e.g. vitest with `vitest run`)
   or `pytest`. Tests must not need a browser or network.
5. Check your work: run `pnpm run build` (and `pnpm run lint` if present) or `pytest`, read the errors, fix
   them, and re-run until clean.
6. Replace the scaffold's README.md with one for this project with sections: Overview, Tech Stack, Setup,
   Usage, Architecture, and "How it was built" — that last section is the first-person build story from
   the plan, not a generic template.
7. Call `finish` only when everything above is done and passing. For web apps, a QA agent then runs the
   production build in a real browser (devicePixelRatio 2), exercises every feature, and sends you its
   bug reports. Fix the root cause of each one — e.g. mouse/canvas coordinate math must convert between
   CSS pixels and device pixels correctly — then call `finish` again.

Rules: every command runs in the project root — do not cd outside it or touch files outside it. Never run
dev servers or watch mode (they never exit). Never run git. Never prompt for input. Keep going with tool
calls until you call `finish`; replying with plain text does not end the task."""


def load_plan(slug: str, base_dir: Path) -> dict:
    plan_path = base_dir / "plans" / f"{slug}.json"
    return json.loads(plan_path.read_text(encoding="utf-8"))


def _initial_user_message(plan: dict, project_dir: Path, previous_failure: str | None) -> str:
    parts = [
        f"Build this project. Plan:\n```json\n{json.dumps(plan, indent=2, ensure_ascii=False)}\n```"
    ]
    existing = workspace.list_files(project_dir) if project_dir.exists() else "(empty)"
    if existing != "(empty)":
        parts.append(
            "The project directory already has work from an earlier attempt. Inspect it and "
            "continue from there rather than starting over; delete files that are clearly broken.\n"
            f"Current files:\n{existing}"
        )
    else:
        parts.append("The project directory is empty.")
    if previous_failure:
        parts.append(f"The last validation of this project failed with:\n{previous_failure}")
    return "\n\n".join(parts)


def _compact(messages: list[dict]) -> None:
    """Shrink old tool traffic in place so long builds fit in context.

    The system prompt and the plan (first two messages) are always kept whole.
    """
    for entry in messages[2:-KEEP_RECENT_MESSAGES]:
        if entry["role"] == "tool" and len(entry["content"]) > 400:
            entry["content"] = entry["content"][:200] + "\n... [older output elided]"
        for call in entry.get("tool_calls", []):
            fn = call["function"]
            if fn["name"] == "write_file" and len(fn["arguments"]) > 400:
                try:
                    path = json.loads(fn["arguments"]).get("path", "?")
                except json.JSONDecodeError:
                    path = "?"
                fn["arguments"] = json.dumps({"path": path, "content": "[elided — read_file to see it]"})


def check_readme(project_dir: Path) -> str | None:
    readme = project_dir / "README.md"
    if not readme.exists():
        return "README.md is missing"
    text = readme.read_text(encoding="utf-8", errors="replace")
    if NEXT_DEFAULT_README in text:
        return "README.md is still the create-next-app default; replace it with this project's README"
    if README_MARKER not in text.lower():
        return 'README.md has no "How it was built" section'
    return None


def check_no_check_bypass(project_dir: Path) -> str | None:
    """A build that passes because type/lint errors were switched off doesn't count."""
    for config in project_dir.glob("next.config.*"):
        text = config.read_text(encoding="utf-8", errors="replace")
        for flag in BYPASS_FLAGS:
            if flag in text:
                return f"{config.name} sets `{flag}`; fix the errors instead of disabling the check"
    return None


def check_tailwind_wired(project_dir: Path) -> str | None:
    """Tailwind installed but not hooked into the build compiles fine and ships
    an unstyled page — nothing else in verification would notice."""
    pkg_path = project_dir / "package.json"
    if not pkg_path.exists():
        return None
    try:
        pkg = json.loads(pkg_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None
    deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}
    if "tailwindcss" not in deps:
        return None
    configs = list(project_dir.glob("next.config.*")) + list(project_dir.glob("postcss.config.*"))
    for config in configs:
        text = config.read_text(encoding="utf-8", errors="replace")
        if "@tailwindcss/turbopack" in text or "@tailwindcss/postcss" in text:
            return None
    return (
        "tailwindcss is installed but not wired into the build (no @tailwindcss/turbopack rule in "
        "next.config or @tailwindcss/postcss in postcss.config), so the app renders unstyled. "
        "Restore the scaffold's Tailwind config."
    )


def acceptance_check(project_dir: Path) -> tuple[bool, str]:
    problem = (
        check_readme(project_dir)
        or check_no_check_bypass(project_dir)
        or check_tailwind_wired(project_dir)
    )
    ok, report = workspace.verify_project(project_dir)
    if problem:
        return False, f"{problem}\n\n{report}"
    return ok, report


def _dispatch(name: str, args: dict, project_dir: Path) -> str:
    if name == "run_command":
        result = workspace.run_command(
            project_dir, args["command"], args.get("timeout_seconds", workspace.DEFAULT_TIMEOUT)
        )
        return workspace.format_command_result(result)
    if name == "write_file":
        return workspace.write_file(project_dir, args["path"], args["content"])
    if name == "read_file":
        return workspace.read_file(project_dir, args["path"])
    if name == "list_files":
        return workspace.list_files(project_dir, args.get("path") or ".")
    return f"error: unknown tool {name!r}"


def run_agent(plan: dict, project_dir: Path, client, previous_failure: str | None = None,
              run_qa: bool = True, known_issues: list[dict] | None = None) -> bool:
    project_dir.mkdir(parents=True, exist_ok=True)
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": _initial_user_message(plan, project_dir, previous_failure)},
    ]
    finish_attempts = 0
    qa_rounds = 0
    open_issues: list[dict] = list(known_issues or [])
    text_only_replies = 0
    last_signature, repeats = None, 0

    for step in range(MAX_STEPS):
        _compact(messages)
        message = chat(client, messages, TOOLS)
        messages.append(assistant_message_dict(message))

        if not message.tool_calls:
            text_only_replies += 1
            if text_only_replies > MAX_TEXT_ONLY_REPLIES:
                logging.warning("[builder] agent stopped calling tools; giving up")
                return False
            messages.append({
                "role": "user",
                "content": "Continue working with the tools. Call `finish` when the project is complete.",
            })
            continue
        text_only_replies = 0

        for call in message.tool_calls:
            name = call.function.name
            try:
                args = json.loads(call.function.arguments or "{}")
            except json.JSONDecodeError as exc:
                result = f"error: arguments were not valid JSON ({exc}); retry the call"
            else:
                logging.info("[builder] step %d: %s %s", step, name, _describe(name, args))
                if name == "finish":
                    ok, report = acceptance_check(project_dir)
                    if not ok:
                        # Only failed checks count: passing ones go to QA, which has its own limit.
                        finish_attempts += 1
                        logging.info("[builder] acceptance failed (attempt %d)", finish_attempts)
                        if finish_attempts >= MAX_FINISH_ATTEMPTS:
                            return False
                        result = f"Not done yet — verification failed. Fix this and call finish again:\n\n{report}"
                    elif not (run_qa and qa.is_web_app(project_dir)):
                        logging.info("[builder] acceptance passed: %s", args.get("summary", ""))
                        return True
                    else:
                        qa_rounds += 1
                        logging.info("[builder] checks passed; QA round %d", qa_rounds)
                        qa_result = qa.run_qa(plan, project_dir, client, previous_issues=open_issues)
                        open_issues = qa.blocking(qa_result.issues)
                        if not open_issues:
                            if qa_result.issues:
                                logging.info("[builder] QA passed with minor issues:\n%s",
                                             qa.format_issues(qa_result.issues))
                            if not qa_result.complete:
                                # Nothing reproducible for the developer to fix; say so loudly.
                                logging.warning("[builder] QA found no blocking bugs but did not finish "
                                                "testing every feature (%s)", qa_result.summary)
                            logging.info("[builder] QA passed: %s", qa_result.summary)
                            return True
                        logging.info("[builder] QA found %d blocking bug(s)", len(open_issues))
                        if qa_rounds >= MAX_QA_ROUNDS:
                            logging.warning("[builder] QA still failing after %d rounds:\n%s",
                                            qa_rounds, qa.format_issues(open_issues))
                            return False
                        result = (
                            "Build and tests pass, but QA tested the running app in a browser and found "
                            "these bugs. Fix each one at its root cause (read the component first), then "
                            "call finish again — QA will re-check them:\n\n" + qa.format_issues(open_issues)
                            + qa.format_diagnostics(qa_result.diagnostics)
                        )
                else:
                    try:
                        result = _dispatch(name, args, project_dir)
                    except (KeyError, ValueError, OSError) as exc:
                        result = f"error: {exc}"
                    signature = (name, call.function.arguments)
                    repeats = repeats + 1 if signature == last_signature else 1
                    last_signature = signature
                    if repeats >= REPEAT_WARNING_AFTER:
                        result += (
                            f"\n\nNote: you have made this exact call {repeats} times in a row and "
                            "the result has not changed. Act on it (edit the file, run the build) "
                            "instead of repeating it."
                        )
            messages.append({"role": "tool", "tool_call_id": call.id, "content": result})

    logging.warning("[builder] ran out of steps (%d)", MAX_STEPS)
    return False


def _describe(name: str, args: dict) -> str:
    if name == "run_command":
        return args.get("command", "")
    if name in ("write_file", "read_file", "list_files"):
        return args.get("path", ".")
    return ""


def _remove_nested_git(project_dir: Path) -> None:
    """A .git inside projects/<slug> would be committed as a broken gitlink."""
    nested = project_dir / ".git"
    if not nested.exists():
        return

    def _force_writable(func, path, _exc):
        Path(path).chmod(stat.S_IWRITE)
        func(path)

    shutil.rmtree(nested, onexc=_force_writable)


def run(base_dir: Path, client, state: dict) -> dict:
    slug = state["project_slug"]
    plan = load_plan(slug, base_dir)
    # Plans written before the planner normalized paths may hold a raw tree.
    plan["structure"] = normalize_structure(plan.get("structure", []))
    project_dir = base_dir / "projects" / slug
    passed = run_agent(plan, project_dir, client, state.pop("last_failure", None))
    _remove_nested_git(project_dir)
    state["phase"] = "validating" if passed else "failed"
    return state


def resume(base_dir: Path, client, state: dict) -> dict:
    return run(base_dir, client, state)
