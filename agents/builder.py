"""Builder: a tool-using development agent with a terminal in the project dir.

Instead of asking the LLM for each file in isolation, the agent scaffolds a
real project (e.g. `create-next-app`), installs dependencies, writes code on
top of the generated structure, and runs builds/tests itself. When it calls
`finish`, the harness independently verifies the project; failures are fed
back so the agent keeps fixing until the project actually works.
"""

import json
import logging
import shutil
import stat
from pathlib import Path

from agents import qa, workspace
from agents.planner import normalize_structure
from utils.llm import assistant_message_dict, chat

MAX_STEPS = 200
MAX_FINISH_ATTEMPTS = 4
MAX_QA_ROUNDS = 4
MAX_TEXT_ONLY_REPLIES = 3
REPEAT_WARNING_AFTER = 3
KEEP_RECENT_MESSAGES = 40
README_MARKER = "how it was built"
BYPASS_FLAGS = ("ignoreBuildErrors", "ignoreDuringBuilds")
NEXT_DEFAULT_README = "bootstrapped with [`create-next-app`]"

NEXT_SCAFFOLD_CMD = (
    'pnpm dlx create-next-app@latest . --ts --tailwind --eslint --app '
    '--src-dir --import-alias "@/*" --use-pnpm --disable-git --yes'
)

